import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import readXlsxFile from 'read-excel-file/node';
import { businessQualityReview } from '../app/lib/business-quality-review.ts';
import { createBusinessAnalysisConfig } from '../app/lib/business-analysis.ts';
import { profileRows } from '../app/lib/tabular-profile.ts';
const fixturePath = fileURLToPath(new URL('../../evaluation/novice_test_files/novice_test_p04.xlsx', import.meta.url));
const [sheet] = await readXlsxFile(fixturePath, {sheet:'orders'});
const profile = profileRows(sheet.data, {fileName:'novice_test_p04.xlsx',fileSize:5452,fileType:'Excel',activeSheet:'orders',sheetNames:['orders']});
const question='比较不同地区的送货成功率';
const config={...createBusinessAnalysisConfig(profile,null,question),entityField:'order_id',groupField:'region',ratioNumerator:{enabled:true,field:'status',operator:'equals',value:'已送达'}};
const review=businessQualityReview(profile,config,question);
const byField=field => review.items.filter(item => profile.qualityIssues.find(issue=>issue.id===item.issueId).field===field);
assert(byField('customer_id').every(item=>item.level==='unrelated'));
assert(byField('order_date').every(item=>item.level==='unrelated'));
assert(byField('amount').every(item=>item.level==='unrelated'));
assert(byField('region').every(item=>item.level==='affecting'));
assert(byField('order_id').every(item=>item.level==='review'));
assert(review.items.filter(item=>item.level==='unrelated').every(item=>item.label.includes('候选口径')));
const trend=businessQualityReview(profile,{...config,analysisType:'trend',aggregation:'count_distinct',timeField:'order_date'},'按月比较去重订单数量');
assert.equal(trend.items.find(item=>item.issueId==='invalid-date-2').level,'affecting');
const customers=businessQualityReview(profile,{...config,aggregation:'count_distinct',entityField:'customer_id'},'按地区比较客户数');
assert.equal(customers.items.find(item=>item.issueId==='missing-1').level,'affecting');
const unbound=businessQualityReview(profile,{...config,entityField:''},question);
assert.equal(unbound.unrelated,0);
assert.equal(unbound.review,profile.qualityIssues.length);
console.log(JSON.stringify({passed:true,ratio:{affecting:review.affecting,review:review.review,unrelated:review.unrelated},dateBecomesRelevantForTrend:true,customerBecomesRelevantForCustomerCount:true,unboundFieldsNeverMarkedUnrelated:true},null,2));
